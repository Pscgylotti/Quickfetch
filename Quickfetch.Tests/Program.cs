using Quickfetch.Core;

var passed = 0;
void Check(bool condition, string message) { if (!condition) throw new Exception(message); passed++; }
ShortcutEntry E(string name, string? path = null) => new(name, path ?? "C:\\Links\\" + name + ".lnk");

var all = new[] { E("CodeRunner"), E("Xcode"), E("Visual Studio Code"), E("Code"), E("Codec"), E("Cdoe"), E("ecod"), E("XYZ") };
var found = SearchMatcher.Search(all, "code");
Check(found[0].Name == "Code", "Exact app name must win.");
Check(found[1].Name == "Visual Studio Code", "A whole word must beat a prefix.");
Check(found[2].Name == "Codec" && found[3].Name == "CodeRunner", "Prefixes must beat internal substrings; short prefixes win ties.");
Check(found[4].Name == "Xcode", "An internal exact substring must beat fuzzy overlap.");
Check(found.Single(x => x.Name == "Cdoe").Tier == 5, "Scattered letters must use the final tier.");
Check(found.Single(x => x.Name == "ecod").Tier == 4, "A continuous partial substring must precede scattered matches.");
Check(!found.Any(x => x.Name == "XYZ"), "No overlapping characters must yield no result.");
Check(SearchMatcher.Search(new[] { E("Telegram") }, "TELE").Single().Tier == 1, "Search must ignore case.");
Check(SearchMatcher.Search(new[] { E("Tencent Meeting") }, "tencentmeeting").Single().ExactName, "Spaces and punctuation in names must be ignored.");
Check(SearchMatcher.CharacterOverlap("a", "aaaa") == 1, "One name character must not count four times.");
Check(SearchMatcher.LongestCommonSubstring("abcdef", "ace") == 1, "Subsequence must not count as a continuous substring.");
Check(SearchMatcher.Search(new[] { E("QQ2"), E("QQ12") }, "2")[0].Name == "QQ2", "Digits must be searchable.");
Check(SearchMatcher.Search(new[] { E("中文"), E("中文Code") }, "").Count == 1, "Names with no ASCII letters or digits must be excluded.");
Check(SearchMatcher.Search(new[] { E("Telegram"), E("QQ") }, "xyz").Count == 0, "An unrelated query must return no matches.");
Check(SearchMatcher.Search(new[] { E("Code", "C:\\B\\Code.lnk"), E("Code", "C:\\A\\Code.lnk") }, "code")[0].Path.Contains("\\A\\"), "Duplicate names must have a stable path tiebreaker.");
var initials = SearchMatcher.Search(new[] { E("AvscTool"), E("Visual Studio Code"), E("VscLauncher"), E("VSC"), E("VisualStudioCode") }, "vsc");
Check(initials.Take(4).Select(x => x.Name).SequenceEqual(new[] { "VSC", "VscLauncher", "Visual Studio Code", "AvscTool" }), "Initials must follow prefix matches and precede internal substrings.");
Check(SearchMatcher.Search(new[] { E("Visual   Studio Code") }, "VS").Single().Tier == 2, "Repeated spaces and initials prefixes must work, ignoring case.");
Check(SearchMatcher.Search(new[] { E("VisualStudioCode") }, "vsc").Single().Tier != 2, "CamelCase alone must not create space-delimited initials.");
Check(SearchMatcher.Search(new[] { E("Studio Visual Code") }, "vsc").Single().Tier != 2, "Initials must follow word order.");
Check(SearchMatcher.Search(new[] { E("Tool 2 Launcher") }, "t2l").Single().Tier == 2, "Digit initials must be supported.");
Check(QueryEditor.Apply("vsc", 3, 0, "backspace") == ("vs", 2), "Backspace must remove the character before the caret.");
Check(QueryEditor.Apply("vsc", 0, 0, "backspace") == ("vsc", 0), "Backspace at the start must be safe.");
Check(QueryEditor.Apply("vsc", 1, 2, "x") == ("vx", 2), "Touch typing must replace a selected range.");
Check(QueryEditor.Apply("vsc", 1, 1, "backspace") == ("vc", 1), "Backspace must remove selected text first.");
Check(QueryEditor.Apply("vsc", 1, 0, "2") == ("v2sc", 2), "Digits must insert at the caret.");
Check(QueryEditor.Apply("vsc", 1, 0, "clear") == ("", 0), "Clear must reset the query and caret.");
Check(QueryEditor.Apply("vsc", 1, 0, "!") == ("vsc", 1), "The compact keyboard must only accept ASCII letters and digits.");
var tap = new DoubleTapTracker();
Check(!tap.Tap("a.lnk", 100, 10, 10, 500) && tap.Tap("a.lnk", 400, 12, 12, 500), "Two nearby taps on the same shortcut must launch.");
Check(!tap.Tap("a.lnk", 500, 10, 10, 500), "The third tap must not launch a second time.");
tap.Reset();
Check(!tap.Tap("a.lnk", 100, 10, 10, 500) && !tap.Tap("b.lnk", 200, 10, 10, 500), "Taps on different shortcuts must not launch.");
tap.Reset(); tap.Tap("a.lnk", 100, 10, 10, 500);
Check(!tap.Tap("a.lnk", 700, 10, 10, 500), "Slow taps must not launch.");
tap.Reset(); tap.Tap("a.lnk", 100, 10, 10, 500);
Check(!tap.Tap("a.lnk", 200, 80, 10, 500), "Distant taps must not launch.");
tap.Reset();
Check(!tap.Tap("a.lnk", 250, 80, 10, 500), "A cancelled or scrolling gesture must clear the double-tap candidate.");
var now = DateTimeOffset.UtcNow;
var recent = UsageRanking.Record(null, now);
var older = new AppUsage(10, now.AddDays(-70), 10);
Check(UsageRanking.Score(recent, now) > UsageRanking.Score(older, now), "Recent usage must outrank sufficiently old frequency.");
var frequent = UsageRanking.Record(UsageRanking.Record(null, now), now);
Check(frequent.Count == 2 && frequent.Weight > recent.Weight, "Repeated successful launches must increase frequency.");
var appMatches = SearchMatcher.Search(new[] { E("Alpha"), E("Beta") }, "");
var history = new Dictionary<string, AppUsage>(StringComparer.OrdinalIgnoreCase) { [E("Beta").Path] = frequent };
Check(UsageRanking.Rank(appMatches, history, now)[0].Name == "Beta", "Usage must order the default app list.");
var wordMatches = SearchMatcher.Search(new[] { E("Code"), E("CodeRunner") }, "code");
history[E("CodeRunner").Path] = frequent;
Check(UsageRanking.Rank(wordMatches, history, now)[0].Name == "Code", "Usage must not override exact-name matching priority.");
var queryPacket = EverythingProtocol.BuildQuery(123, 456, "文件 .txt", 14, 500);
Check(queryPacket.Length == 28 + System.Text.Encoding.Unicode.GetByteCount("文件 .txt\0"), "IPC requests must encode Unicode search text after the Query2 header.");
Check(System.Buffers.Binary.BinaryPrimitives.ReadUInt32LittleEndian(queryPacket.AsSpan(24)) == 14, "IPC sort must be transmitted to Everything.");
bool malformedRejected = false;
try { EverythingProtocol.Parse(new byte[5]); } catch (System.IO.InvalidDataException) { malformedRejected = true; }
Check(malformedRejected, "Malformed IPC responses must be rejected.");
Check(FileEntry.FormatSize(1024) == "1 KB" && FileEntry.FormatSize(0) == "0 B", "File sizes must format predictably.");
GestureChecks.Run(Check);
Console.WriteLine($"PASS: {passed} ranking/editing/touch/gesture/IPC checks");
